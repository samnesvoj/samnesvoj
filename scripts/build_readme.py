def build(loc: str) -> str:
    c, tx = COPY[loc], TX[loc]
    pre = "" if loc == "en" else f"{loc}/"

    def pic(name: str, alt: str, width: int | None = None, shared: bool = False) -> str:
        p = name if shared else f"{pre}{{theme}}/{name}"
        w = f' width="{width}"' if width else ""
        return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="{RAW}{p.format(theme="dark")}">'
                f'<img src="assets/{p.format(theme="light")}"{w} alt="{alt}"></picture>')

    def link(href: str | None, inner: str) -> str:
        return f'<a href="{href}">{inner}</a>' if href else inner

    out: list[str] = []
    A = out.append
    A(pic("hero.svg", "sonya. — " + tx["sub"], FULL))
    A(f'\n<p align="center"><sub>{c["switch"]}</sub></p>\n')

    A(pic("h-about.svg", tx["headings"]["about"]))
    A("\n" + c["about"] + "\n")
    A(pic("g-background.svg", tx["background"]))
    A("<p>")
    for key, text in tx["badges"].items():
        A(pic(f"badge-{key}.svg", text))
    A("</p>\n")

    A(pic("h-stack.svg", tx["headings"]["stack"]) + "\n")
    for key, en, ru, keys, also_en, also_ru in STACK:
        also = also_en if loc == "en" else also_ru
        A(pic(f"g-{key}.svg", en if loc == "en" else ru))
        A("<p>")
        for k in keys:
            A(f'<img src="assets/stack/{k}.svg" width="46" alt="{LOGOS[k][0]}" title="{LOGOS[k][0]}">')
        if also:
            A("<br>")
            A(f"<sub>{c['also']} · {also}</sub>")
        A("</p>\n")
    A(pic("g-spoken.svg", tx["spoken_label"]))
    A("<p>")
    for i, (name, jp, level) in enumerate(tx["spoken"]):
        A(pic(f"lang-{i}.svg", f"{name} {jp} {level}".replace("  ", " ")))
    A("</p>\n")

    A(pic("h-hardware.svg", tx["headings"]["hardware"]) + "\n")
    A(c["hardware"] + "\n")
    A(pic("hardware.svg", tx["headings"]["hardware"], FULL) + "\n")

    A(pic("h-projects.svg", tx["headings"]["projects"]) + "\n")
    A(link(SONYA_SITE, pic("featured-sonya.svg", c["featured_alt"], FULL)) + "\n")
    keys = list(CARD_STACKS)
    for i in range(0, len(keys), 2):
        A("<p>")
        for k in keys[i:i + 2]:
            title, sub, desc, _ = tx["cards"][k]
            A(link(LINKS.get(k), pic(f"card-{k}.svg", f"{title} — {sub}", 400)))
        A("</p>\n")
    A(f"<sub>{c['links']}</sub>\n")

    A(pic("h-activity.svg", tx["headings"]["activity"]) + "\n")
    A(c["activity"] + "\n")
    A("<p>")
    A(link("https://github.com/samnesvoj", pic("stats.svg", tx["gh_label"], 400)))
    A(link("https://www.codewars.com/users/ex-lain", pic("codewars.svg", "codewars · ex-lain", 400)))
    A("</p>\n")
    A(pic("activity.svg", tx["contrib_label"], FULL) + "\n")

    A(pic("h-learning.svg", tx["headings"]["learning"]) + "\n")
    A(pic("learning.svg", ", ".join(x[0] for x in tx["learning"]), FULL) + "\n")
    A(c["learning"] + "\n")

    A(pic("h-find.svg", tx["headings"]["find"]) + "\n")
    A(c["contact"] + "\n")
    A("<p>")
    for key, href, alt in (("telegram", "https://t.me/removed", "telegram: @removed"),
                           ("github", "https://github.com/samnesvoj", "github: @samnesvoj"),
                           ("codewars", "https://www.codewars.com/users/ex-lain", "codewars: ex-lain"),
                           ("email", "mailto:removed", "email: removed")):
        A(link(href, pic(f"{{theme}}/pill-{key}.svg", alt, shared=True)))
    A("</p>\n")

    A(pic("footer.svg", tx["thanks"] + " — またね", FULL) + "\n")
    A(f'<div align="center">\n<sub>{c["credits"]}</sub>\n</div>')
    return "\n".join(out) + "\n"


def main() -> None:
    for loc in COPY:
        (ROOT / COPY[loc]["file"]).write_text(build(loc), encoding="utf-8")
        print(f"  wrote {COPY[loc]['file']}")


if __name__ == "__main__":
    main()
